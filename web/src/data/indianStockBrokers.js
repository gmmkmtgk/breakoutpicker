export function brokerMatchesSearch(b, q) {
  if (!q.trim()) return true;
  const s = q.trim().toLowerCase();
  return (
    b.brand.toLowerCase().includes(s) ||
    b.legalName.toLowerCase().includes(s) ||
    b.idealFor.toLowerCase().includes(s) ||
    b.platforms.some((p) => p.toLowerCase().includes(s))
  );
}

export function segmentFilter(b, segKey) {
  if (!segKey || segKey === 'all') return true;
  return b.segments.includes(segKey);
}
